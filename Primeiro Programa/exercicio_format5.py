'''CONSTRUA UM PROGRAMA QUE LEIA 2 NUMEROS REAIS.
CALCULE A SOMA DOS DOIS VALORES E O PRODUTO ENTRE ELES'''

num1 = float(input("digite o primeiro numero real: "))
num2 = float(input("digite o segundo numero real: "))

soma = num1 + num2 
produto = num1 * num2 

print(f"soma entre os dois numeros é: {soma:.2f}")
print(f"produto entre os dois numeros é: {produto:.2f}")